import fs from "node:fs";
import path from "node:path";

const WIDTH = 1024;
const HEIGHT = 512;
const OUTPUT_PATH = path.resolve(
    process.argv[2] ?? "src/assets/ibl-shadows/white.hdr",
);

const normalize = ([x, y, z]) => {
    const length = Math.hypot(x, y, z);
    return [x / length, y / length, z / length];
};

const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];

const gaussianLobe = (direction, center, sigmaRadians) => {
    const angle = Math.acos(Math.max(-1, Math.min(1, dot(direction, center))));
    return Math.exp(-(angle * angle) / (2 * sigmaRadians * sigmaRadians));
};

// MMD_modoki's default camera looks at the model from -Z. The strong, broad
// +Z source therefore behaves as a neutral studio back light. It gives
// Babylon PBR translucency a meaningful opposite-side irradiance sample while
// a weaker -Z source keeps ordinary PBR materials readable from the front.
const BACK_KEY_DIRECTION = normalize([-0.22, 0.32, 0.92]);
const FRONT_FILL_DIRECTION = normalize([0.28, 0.18, -0.94]);
const SIDE_RIM_DIRECTION = normalize([-0.86, 0.42, -0.28]);

const degrees = (value) => value * Math.PI / 180;

const evaluateRadiance = (direction) => {
    const up = Math.max(0, direction[1]);
    const down = Math.max(0, -direction[1]);
    const ambient = 0.34 + 0.10 * up + 0.04 * down;
    const backKey = 6.4 * gaussianLobe(direction, BACK_KEY_DIRECTION, degrees(38));
    const frontFill = 1.35 * gaussianLobe(direction, FRONT_FILL_DIRECTION, degrees(58));
    const sideRim = 1.8 * gaussianLobe(direction, SIDE_RIM_DIRECTION, degrees(30));
    return ambient + backKey + frontFill + sideRim;
};

const toRgbe = (radiance) => {
    if (!Number.isFinite(radiance) || radiance <= 1e-32) {
        return [0, 0, 0, 0];
    }
    const exponent = Math.floor(Math.log2(radiance)) + 1;
    const scale = 256 / (2 ** exponent);
    const channel = Math.max(0, Math.min(255, Math.round(radiance * scale)));
    return [channel, channel, channel, exponent + 128];
};

const encodeChannelRle = (channel) => {
    const bytes = [];
    let index = 0;
    while (index < channel.length) {
        let runLength = 1;
        while (
            index + runLength < channel.length
            && runLength < 127
            && channel[index + runLength] === channel[index]
        ) {
            runLength += 1;
        }

        if (runLength >= 4) {
            bytes.push(128 + runLength, channel[index]);
            index += runLength;
            continue;
        }

        const literalStart = index;
        while (index < channel.length && index - literalStart < 128) {
            runLength = 1;
            while (
                index + runLength < channel.length
                && runLength < 127
                && channel[index + runLength] === channel[index]
            ) {
                runLength += 1;
            }
            if (runLength >= 4) break;
            index += Math.min(runLength, 128 - (index - literalStart));
        }

        const literalLength = index - literalStart;
        bytes.push(literalLength);
        for (let offset = literalStart; offset < index; offset += 1) {
            bytes.push(channel[offset]);
        }
    }
    return bytes;
};

const chunks = [];
const header = [
    "#?RADIANCE",
    "# Procedurally generated; contains no photographed scene or third-party image",
    "SOFTWARE=MMD_modoki bundled studio IBL generator",
    "AUTHOR=MMD_modoki contributors",
    "COPYRIGHT=Copyright (c) 2026 MMD_modoki contributors",
    "LICENSE=MIT",
    "SOURCE=Procedurally generated by scripts/generate-bundled-studio-hdr.mjs",
    "DESCRIPTION=Neutral studio IBL with broad back key, front fill, and side rim",
    "FORMAT=32-bit_rle_rgbe",
    "EXPOSURE=1.000000",
    "",
    `-Y ${HEIGHT} +X ${WIDTH}`,
    "",
].join("\n");
chunks.push(Buffer.from(header, "ascii"));

for (let y = 0; y < HEIGHT; y += 1) {
    const scanline = [
        new Uint8Array(WIDTH),
        new Uint8Array(WIDTH),
        new Uint8Array(WIDTH),
        new Uint8Array(WIDTH),
    ];

    // Babylon's panorama conversion inverts the source Y coordinate. Author
    // the panorama in that coordinate convention so +Y remains the upper sky.
    const phi = Math.PI * (HEIGHT - y - 0.5) / HEIGHT;
    const sinPhi = Math.sin(phi);
    for (let x = 0; x < WIDTH; x += 1) {
        const theta = ((x + 0.5) / WIDTH * 2 - 1) * Math.PI;
        const direction = [
            sinPhi * Math.cos(theta),
            Math.cos(phi),
            sinPhi * Math.sin(theta),
        ];
        const rgbe = toRgbe(evaluateRadiance(direction));
        for (let channel = 0; channel < 4; channel += 1) {
            scanline[channel][x] = rgbe[channel];
        }
    }

    chunks.push(Buffer.from([2, 2, WIDTH >> 8, WIDTH & 0xff]));
    for (const channel of scanline) {
        chunks.push(Buffer.from(encodeChannelRle(channel)));
    }
}

fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
fs.writeFileSync(OUTPUT_PATH, Buffer.concat(chunks));
process.stdout.write(`${OUTPUT_PATH}\n`);
